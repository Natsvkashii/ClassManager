import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, '..', '..'))

INDEX_HTML_PATH = os.path.join(REPO_ROOT, 'Windows-Version', 'src', 'index.html')
LOGO_PNG_PATH = os.path.join(REPO_ROOT, 'Windows-Version', 'src', 'logo.png')
APP_ICON_PATH = os.path.join(REPO_ROOT, 'Windows-Version', 'assets', 'AppIcon.ico')
OUTPUT_HEADER_PATH = os.path.join(SCRIPT_DIR, 'assets_bundle.h')

def file_to_c_array(name, filepath, out_fp):
    with open(filepath, 'rb') as f:
        data = f.read()
    
    out_fp.write(f'// File: {os.path.basename(filepath)} ({len(data)} bytes)\n')
    out_fp.write(f'const size_t {name}_LEN = {len(data)};\n')
    out_fp.write(f'const unsigned char {name}[] = {{\n')
    
    CHUNK_SIZE = 16
    for i in range(0, len(data), CHUNK_SIZE):
        chunk = data[i:i+CHUNK_SIZE]
        hex_str = ', '.join(f'0x{b:02x}' for b in chunk)
        if i + CHUNK_SIZE < len(data):
            out_fp.write(f'    {hex_str},\n')
        else:
            out_fp.write(f'    {hex_str}\n')
    out_fp.write('};\n\n')

import re

def get_app_version_and_channel():
    models_swift = os.path.join(REPO_ROOT, 'Sources', 'Models.swift')
    ver = "26.10.4-018"
    channel = "UNSTABLE"
    if os.path.exists(models_swift):
        with open(models_swift, 'r', encoding='utf-8') as f:
            c = f.read()
        m_v = re.search(r'public\s+static\s+let\s+appVersion\s*=\s*"([^"]+)"', c)
        if m_v:
            ver = m_v.group(1)
        m_ch = re.search(r'public\s+static\s+let\s+appChannel\s*=\s*"([^"]+)"', c)
        if m_ch:
            channel = m_ch.group(1).upper()
    return ver, channel

def main():
    print(f"Bundling assets into {OUTPUT_HEADER_PATH}...")
    ver, channel = get_app_version_and_channel()
    if channel == "STABLE":
        window_title = f"ClassDesk v{ver}"
    else:
        window_title = f"ClassDesk v{ver} [{channel}]"
    with open(OUTPUT_HEADER_PATH, 'w') as out_fp:
        out_fp.write('// Auto-generated by generate_assets.py - DO NOT EDIT MANUALLY\n')
        out_fp.write('// Author: Guaira Jaramillo Nitoglia (guaira.jaramillo.nitoglia@gmail.com)\n\n')
        out_fp.write('#pragma once\n')
        out_fp.write('#include <stddef.h>\n\n')
        out_fp.write(f'#define BUNDLED_APP_VERSION L"{ver}"\n')
        out_fp.write(f'#define BUNDLED_APP_CHANNEL L"{channel}"\n')
        out_fp.write(f'#define BUNDLED_WINDOW_TITLE L"{window_title}"\n\n')
        
        file_to_c_array('ASSET_INDEX_HTML', INDEX_HTML_PATH, out_fp)
        file_to_c_array('ASSET_LOGO_PNG', LOGO_PNG_PATH, out_fp)
        file_to_c_array('ASSET_APP_ICON_ICO', APP_ICON_PATH, out_fp)
        
    print(f"Generated {OUTPUT_HEADER_PATH} successfully!")

if __name__ == '__main__':
    main()
